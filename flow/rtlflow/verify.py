def clean(module_name: str | None = None, all_modules: bool = False) -> int:
    if all_modules:
        ws = workspace.require_workspace()
        targets = ws.modules()
    else:
        _, module = workspace.resolve(module_name)
        targets = [module]

    for module in targets:
        removed = []
        for path in (module.rundir, module.lintdir):
            if not path.is_dir():
                continue
            for entry in path.iterdir():
                if entry.name in (".gitkeep", "waivers.vlt"):
                    continue
                if entry.is_dir():
                    shutil.rmtree(entry)
                else:
                    entry.unlink()
                removed.append(entry.name)
        ui.step(f"Cleaned: {module.name}")
        ui.note(f"removed {len(removed)} entry/entries" if removed else "was already clean")
    return 0
