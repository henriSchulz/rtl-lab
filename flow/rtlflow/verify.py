def lint(module_name: str | None = None, fix_top: bool = True) -> int:
    _, module = workspace.resolve(module_name)
    cfg = module.cfg["lint"]

    if cfg["tool"] != "verilator":
        raise Abort(
            f"linting with '{cfg['tool']}' is not wired up yet",
            hint="Currently supported: verilator",
        )

    binary = tools.require("verilator")
    sources = module.sources("design")
    if sources.is_empty():
        raise Abort(
            f"{module.name}: {module.cfg['sources']['design']} lists no source files",
            hint=f"Add a module with `flow add rtl <name> {module.name}`.",
        )

    argv = [binary, "--lint-only", "-Wall"]
    if not cfg["fatal"]:
        argv.append("-Wno-fatal")
    if fix_top and module.top_design:
        argv += ["--top-module", module.top_design]
    for incdir in sources.incdirs:
        argv.append(f"+incdir+{incdir}")
    for name, value in sources.defines.items():
        argv.append(f"+define+{name}" + (f"={value}" if value else ""))
    argv += [str(a) for a in cfg["args"]]

    waivers = module.path(cfg["waivers"])
    if waivers.is_file():
        argv.append(str(waivers))

    argv += [str(src) for src in sources.sources]

    logdir = module.lintdir
    logdir.mkdir(parents=True, exist_ok=True)
    log = logdir / f"{module.name}.log"

    ui.step(f"Lint: {module.name}  ({len(sources.sources)} file(s))")
    code = tools.run(argv, cwd=module.root, log=log)

    if code == 0:
        ui.ok(f"clean  ->  {log.relative_to(module.root)}")
    else:
        ui.fail(f"lint failed (exit {code})  ->  {log.relative_to(module.root)}")
    return code


