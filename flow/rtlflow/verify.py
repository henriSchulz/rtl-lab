"""Lint, simulation, waveforms and cleanup."""

from __future__ import annotations

import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

from . import meta, tools, ui, workspace
from .ui import Abort

WAVE_SUFFIXES = (".fst", ".vcd", ".ghw")
VIEWERS = ("surfer", "gtkwave")

FRAMEWORKS = ("cocotb", "sv")

# Log of a plain SystemVerilog run; `flow ls` uses it as the "was simulated" mark.
SIM_LOG = "sim.log"
BUILD_LOG = "build.log"

# How a SystemVerilog testbench reports its verdict (see templates/sv_tb.sv).
PASS_MARKER = "TEST PASSED"
FAIL_MARKERS = ("TEST FAILED", "%Error", "$fatal", "Fatal:")

RUNNER = '''#!/usr/bin/env python3
"""Generated by `flow sim` on {stamp} -- edits here are overwritten."""

import sys
from pathlib import Path

try:
    from cocotb_tools.runner import get_runner          # cocotb >= 2.0
except ImportError:  # pragma: no cover
    try:
        from cocotb.runner import get_runner            # cocotb 1.7 / 1.8
    except ImportError:
        sys.exit("cocotb is not installed  ->  pip install cocotb")

runner = get_runner({simulator!r})

runner.build(
    verilog_sources=[Path(p) for p in {sources!r}],
    includes=[Path(p) for p in {includes!r}],
    defines={defines!r},
    build_args={build_args!r},
    hdl_toplevel={top!r},
    build_dir={build!r},
    timescale={timescale!r},
    waves={waves!r},
    always=True,
)

runner.test(
    hdl_toplevel={top!r},
    test_module={modules!r},
    test_dir={testdir!r},
    build_dir={build!r},
    results_xml={results!r},
    test_args={test_args!r},
    plusargs={plusargs!r},
    testcase={testcase!r},
    waves={waves!r},
)
'''


