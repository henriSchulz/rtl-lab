def _newest_wave(rundir: Path) -> Path | None:
    candidates = [
        path
        for path in rundir.rglob("*")
        if path.is_file() and path.suffix in WAVE_SUFFIXES
    ]
    return max(candidates, key=lambda p: p.stat().st_mtime, default=None)


def wave(module_name: str | None = None, viewer: str | None = None) -> int:
    _, module = workspace.resolve(module_name)
    target = _newest_wave(module.rundir)

    if target is None:
        raise Abort(
            f"{module.name}: no waveform in {module.cfg['sim']['rundir']}",
            hint="Simulate first: `flow sim`",
        )

    chosen = viewer or next((v for v in VIEWERS if tools.find(v)), None)
    if chosen is None:
        raise Abort(
            "No waveform viewer found",
            hint="Install one with: pacman -S gtkwave  (or: paru -S surfer-bin)",
        )
    tools.require(chosen)

    ui.step(f"Waveform: {target.relative_to(module.root)}")
    tools.spawn([chosen, str(target)])
    return 0


